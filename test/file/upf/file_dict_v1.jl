using PseudoPotentialIO: upf1_to_dict

@testset "UPF v1 dictionaries" begin
    # mesh of 3; two projectors (l = 0, 1), the first with cutoff radii and a label
    upf1(type, nlcc, extra) = """
    <PP_INFO>
      Generated by hand
    </PP_INFO>
    <PP_HEADER>
       0                   Version Number
       B                   Element
       $type               pseudopotential
       $nlcc               Nonlinear Core Correction
     SLA  PW   PBX  PBC    PBE  Exchange-Correlation functional
        3.00000000000      Z valence
       -5.00000000000      Total energy
        20.0000    80.0000 Suggested cutoff for wfc and rho
        1                  Max angular momentum component
        3                  Number of points in mesh
        2    2             Number of Wavefunctions, Number of Projectors
     Wavefunctions         nl  l   occ
                           2S  0  2.00
                           2P  1  1.00
    </PP_HEADER>
    <PP_MESH>
      <PP_R>
      0.1  0.2
      0.3
      </PP_R>
      <PP_RAB>
      0.1  0.1  0.1
      </PP_RAB>
    </PP_MESH>
    <PP_NLCC>
      1.0D0  2.0D0  3.0D0
    </PP_NLCC>
    <PP_LOCAL>
      -1.0  -2.0  -3.0
    </PP_LOCAL>
    <PP_NONLOCAL>
      <PP_BETA>
        1    0             Beta    L
         2
        0.5  0.6
        1.20  1.30         Rcut   Rcut_US
        2S                 Label
      </PP_BETA>
      <PP_BETA>
        2    1             Beta    L
         3
        0.7  0.8  0.9
      </PP_BETA>
      <PP_DIJ>
        2                  Number of nonzero Dij
        1    1  4.0
        1    2  5.0
      </PP_DIJ>
    $extra
    </PP_NONLOCAL>
    <PP_PSWFC>
    2S    0  2.00          Wavefunction
      0.1  0.2  0.3
    2P    1  1.00          Wavefunction
      0.4  0.5  0.6
    </PP_PSWFC>
    <PP_RHOATOM>
      0.01  0.02  0.03
    </PP_RHOATOM>
    <PP_ADDINFO>
      2S  1  0  0.50  2.00
      2P  2  1  1.50  1.00
      0  0.50
      1  1.50
      -7.0  100.0  3.0  0.0125
    </PP_ADDINFO>
    """
    d = upf1_to_dict(upf1("NC", "T", ""))
    h = d["header"]
    @test d["version"] == "1.old" && d["info"]["content"] == "  Generated by hand"
    @test h["element"] == "B" && h["pseudo_type"] == "NC" && !h["is_ultrasoft"]
    @test h["core_correction"] && h["functional"] == "SLA  PW   PBX  PBC"
    @test h["z_valence"] === 3.0 && h["rho_cutoff"] === 80.0 && h["number_of_proj"] === 2
    @test d["mesh"]["r"] == [0.1, 0.2, 0.3]  # over two lines
    @test d["nlcc"] == [1.0, 2.0, 3.0]
    b1, b2 = d["nonlocal"]["beta"]
    @test b1["content"] == [0.5, 0.6, 0.0]  # zeros after the cutoff index
    @test b1["cutoff_radius"] === 1.2 && b1["ultrasoft_cutoff_radius"] === 1.3
    @test b1["label"] == "2S"
    @test !haskey(b2, "label") && b2["angular_momentum"] === 1
    @test d["nonlocal"]["dij"] == [4.0, 5.0, 5.0, 0.0]
    @test [c["label"] for c in d["pswfc"]["chi"]] == ["2S", "2P"]
    # spin-orbit, and the mesh parameters
    @test h["has_so"] && h["relativistic"] == "full"
    @test [w["jchi"] for w in d["spin_orb"]["relwfc"]] == [0.5, 1.5]
    @test [b["jjj"] for b in d["spin_orb"]["relbeta"]] == [0.5, 1.5]
    @test d["mesh"]["dx"] === 0.0125

    file = UpfFile(IOBuffer(upf1("NC", "T", "")))
    @test file isa UpfFile && file.version == "1.old" && has_spin_orbit(file)
    @test file.nonlocal.betas[1].label == "2S" && file.mesh.zmesh == 3.0

    # an obsolete PP_ADDINFO (j is not l ± 1/2) is ignored
    obsolete = replace(upf1("NC", "T", ""), "2S  1  0  0.50" => "2S  1  0  0.00")
    d = upf1_to_dict(obsolete)
    @test !d["header"]["has_so"] && !haskey(d, "spin_orb") && !haskey(d["mesh"], "dx")

    # ultrasoft, with the augmentation functions for each l (each l on its own lines)
    qij(i, j, l) = """
            $i    $j    $l        i  j  (l(j))
         0.25    Q_int
    """
    with_l = """
      <PP_QIJ>
        0     nqf
    $(qij(1, 1, 0))  1 2 3
    $(qij(1, 2, 1))  4 5 6
    $(qij(2, 2, 1))  7 8 9
      10 11 12
      13 14 15
      </PP_QIJ>
      <PP_QIJ_WITH_L>
      </PP_QIJ_WITH_L>
    """
    aug = upf1_to_dict(upf1("US", ".false.", with_l))["nonlocal"]["augmentation"]
    @test aug["q_with_l"] && aug["nqf"] == 0 && aug["q"] == fill(0.25, 4)
    @test [(f["first_index"], f["second_index"], f["angular_momentum"]) for f in aug["qijl"]] ==
          [(1, 1, 0), (1, 2, 1), (2, 2, 0), (2, 2, 1), (2, 2, 2)]
    @test aug["qijl"][end]["content"] == [13.0, 14.0, 15.0]
    # the l of Q(1, 2) must be that of projector 2
    @test_throws ErrorException upf1_to_dict(upf1("US", "F", replace(with_l, "    1    2    1" => "    1    2    0")))
    @test_throws ErrorException upf1_to_dict(replace(upf1("NC", "T", ""), "  0.1  0.2\n  0.3" => "  0.1  0.2"))
end
